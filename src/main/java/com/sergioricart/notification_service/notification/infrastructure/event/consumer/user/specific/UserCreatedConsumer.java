package com.sergioricart.notification_service.notification.infrastructure.event.consumer.user.specific;

import com.sergioricart.commons.application.Mediator;
import com.sergioricart.commons.infrastructure.event.consumer.EventSpecificConsumer;
import com.sergioricart.notification_service.notification.aplication.kafka.user.created.UserCreatedCommand;
import com.sergioricart.notification_service.notification.infrastructure.event.mapper.user.UserEventMapper;
import com.sergioricart.user_service.autogenerated.events.user.UserCreatedEvent;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.messaging.Message;
import org.springframework.stereotype.Component;

@Component
@Slf4j
@RequiredArgsConstructor
public class UserCreatedConsumer implements EventSpecificConsumer<UserCreatedEvent> {

    private final Mediator mediator;

    private final UserEventMapper userEventMapper;

    @Override
    public String getSchema() {
        return UserCreatedEvent.class.getTypeName();
    }

    @Override
    public void accept(Message<UserCreatedEvent> message) {

        UserCreatedEvent event = message.getPayload();

        log.info("Usuario creado: {} {}, email: {}", event.getFirstName(), event.getLastName(), event.getEmail());

        UserCreatedCommand command = userEventMapper.mapToUserCreatedCommand(event);

        mediator.dispatch(command);

    }
}
